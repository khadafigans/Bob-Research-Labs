	"evidence_version ，。。"

// upgradeReporterTriggerMessage migrates stock reporter tool-call messages to the
// current English default (evidence_version + EN). User-edited messages are left alone.
func (s *Server) upgradeReporterTriggerMessage() {
	const flag = "reporter_trigger_english_v1"
	if v, _, _ := s.m.pg.GetSetting(flag); v == "true" {
		return
	}
	defer func() { _ = s.m.pg.SetSetting(flag, "true") }()
	triggers, err := s.m.pg.ListTriggersFor("reporter")
	if err != nil {
		log.Printf("[reporter] failed to list triggers: %v", err)
		return
	}
	for _, t := range triggers {
		if !t.OnToolCall {
			continue
		}
		switch t.ToolCallMessage {
		case reporterToolCallMessageV1, reporterToolCallMessageCNV2:
			// stock defaults only
		default:
			continue
		}
		t.ToolCallMessage = reporterToolCallMessage
		if err := s.m.pg.UpdateTrigger(t); err != nil {
			log.Printf("[reporter] failed to upgrade trigger message: %v", err)
			return
		}
		log.Printf("[reporter] trigger message upgraded to English (evidence_version)")
	}
}

